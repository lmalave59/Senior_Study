df = pd.read_csv(io.StringIO(data))

# Total IP score
q_cols = [col for col in df.columns if str(col).replace('.','').isdigit()]
df['IP_Score'] = df[q_cols].sum(axis=1)

# Group
df['Group'] = np.where(df['Major field of study'].str.contains('Computer Science', case=False), 'CS Seniors', 'Baseball Athletes')

# GPA numeric
df['GPA'] = pd.to_numeric(df['Overall GPA'], errors='coerce')

# Severity categories
def severity(score):
    if score <= 40: return 'Few'
    elif score <= 60: return 'Moderate'
    elif score <= 80: return 'Frequent'
    else: return 'Intense'
df['Severity'] = df['IP_Score'].apply(severity)

# ========= FIGURE 1 =========
plt.figure(figsize=(9,6))
plt.hist(df['IP_Score'], bins=10, edgecolor='black', color='#3498db')
plt.title('Figure 1. Distribution of Impostor Phenomenon Scores (n=28)', fontsize=14, fontweight='bold')
plt.xlabel('Total IP Score (20–100)'); plt.ylabel('Number of Participants')
plt.grid(axis='y', alpha=0.3)
plt.tight_layout(); plt.savefig('Figure1_Histogram.png', dpi=300, bbox_inches='tight'); plt.close()

# ========= FIGURE 2 =========
valid = df.dropna(subset=['GPA'])
r, p = stats.pearsonr(valid['GPA'], valid['IP_Score'])
plt.figure(figsize=(9,6))
sns.regplot(x='GPA', y='IP_Score', data=valid, scatter_kws={'s':80})
plt.title(f'Figure 2. GPA vs Impostor Score (n=26)\nr = {r:.2f}, p = {p:.3f}', fontsize=14, fontweight='bold')
plt.xlabel('Overall GPA'); plt.ylabel('Total IP Score')
plt.tight_layout(); plt.savefig('Figure2_Scatter.png', dpi=300, bbox_inches='tight'); plt.close()

# ========= FIGURE 3 =========
means = df.groupby('Group')['IP_Score'].mean()
stds  = df.groupby('Group')['IP_Score'].std()
tstat, pval = stats.ttest_ind(df[df['Group']=='CS Seniors']['IP_Score'],
                              df[df['Group']=='Baseball Athletes']['IP_Score'], equal_var=False)
plt.figure(figsize=(8,6))
plt.bar(['Baseball Athletes','CS Seniors'], means, yerr=stds, capsize=10, color=['#3498db','#e67e22'])
plt.title(f'Figure 3. Mean IP Score by Group\nt = {tstat:.2f}, p = {pval:.3f}', fontsize=14, fontweight='bold')
plt.ylabel('Mean Total IP Score')
plt.tight_layout(); plt.savefig('Figure3_Means.png', dpi=300, bbox_inches='tight'); plt.close()

# ========= FIGURE 4 =========
