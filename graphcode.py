plt.tight_layout(); plt.savefig('Figure3_NEWBoxplot.png', dpi=300, bbox_inches='tight'); plt.close()

# ========= FIGURE 5 – Stacked Severity % =========
order = ['Few','Moderate','Frequent','Intense']
counts = pd.crosstab(df['Group'], df['Severity'])[order]
perc = counts.div(counts.sum(axis=1), axis=0) * 100
ax = perc.plot(kind='barh', stacked=True, figsize=(10,5), color=['#d5dbdb','#85c1e2','#3498db','#1a5276'])
plt.title('Figure 3. Impostor Severity Category by Group', fontsize=14, fontweight='bold')
plt.xlabel('Percentage of Participants (%)')
plt.legend(title='Severity', bbox_to_anchor=(1,1))
plt.tight_layout(); plt.savefig('Figure4_NEWSeverity.png', dpi=300, bbox_inches='tight'); plt.close()

# ========= FIGURE 6 – Top 5 Questions =========
means_q = df.groupby('Group')[q_cols].mean()
diff = means_q.loc['CS Seniors'] - means_q.loc['Baseball Athletes']
top5 = diff.abs().nlargest(5).index
top_diff = diff[top5]
plt.figure(figsize=(10,6))
top_diff.sort_values().plot(kind='barh', color='#e74c3c', alpha=0.8)
plt.title('Figure 5. Top 5 Questions Where CS Students Scored Higher', fontsize=14, fontweight='bold')
